#!/usr/bin/env python3
"""Generates src/theme/presets.rs from .impeccable/design.json (colour themes).

Run from the repository root:  python3 crates/printdex-app/tools/gen_presets.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = ROOT / "crates/printdex-app/src/theme/presets.rs"
data = json.loads((ROOT / ".impeccable/design.json").read_text())["extensions"]["colorThemes"]

VARIANTS = {
    "graphite": "GraphiteSignal",
    "frost": "VioletFrost",
    "quartz": "SmokedQuartz",
    "seaglass": "SeaGlass",
    "resin": "AmberResin",
    "rose": "RosePetg",
    "glacier": "Glacier",
}
FIELDS = ["ground", "surface", "tray", "rail", "rail-hi"]
ACCENT = ["accent", "accent-soft", "accent-ink", "primary", "primary-hi", "on-primary"]


def tokens(mode, solid):
    glass = mode["glass"]
    acc = mode["accent"]
    fb = mode["solidFallback"]
    out = []
    for f in FIELDS:
        v = fb[f]["srgb"] if solid else glass[f]["srgb"]
        out.append((f.replace("-", "_"), v))
    for f in ACCENT:
        v = acc[f]["srgb"]
        if solid and f in fb:
            v = fb[f]["srgb"]
        out.append((f.replace("-", "_"), v))
    return out


lines = [
    "// @generated by tools/gen_presets.py from .impeccable/design.json. Do not edit.",
    "",
    "use super::{ColorTheme, ThemeSet, ThemeTokens, hex};",
    "",
    "/// Glass and solid tokens for every colour theme, light then dark.",
    "pub(super) fn preset(theme: ColorTheme) -> (ThemeSet, ThemeSet) {",
    "    match theme {",
]
for key, variant in VARIANTS.items():
    t = data[key]
    lines.append(f"        ColorTheme::{variant} => (")
    for m in ("light", "dark"):
        lines.append("            ThemeSet {")
        for kind, solid in (("glass", False), ("solid", True)):
            lines.append(f"                {kind}: ThemeTokens {{")
            for name, v in tokens(t[m], solid):
                lines.append(f'                    {name}: hex("{v.lower()}"),')
            lines.append("                },")
        lines.append("            },")
    lines.append("        ),")
lines += ["    }", "}", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT}")
